    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        try {

    String nombre = txtNombre.getText();
    String descripcion = txtDescripcion.getText();
    double precio = Double.parseDouble(txtPrecio.getText());
    int stock = Integer.parseInt(txtStock.getText());
    int stockMinimo = Integer.parseInt(txtStockMinimo.getText());
    int idProveedor = Integer.parseInt(txtProveedor.getText());

    Producto producto = new Producto(
            0,
            nombre,
            descripcion,
            precio,
            stock,
            stockMinimo,
            idProveedor
    );

    ProductoDAO productoDAO = new ProductoDAO();
    productoDAO.agregarProducto(producto);

    cargarProductos();

    txtNombre.setText("");
    txtDescripcion.setText("");
    txtPrecio.setText("");
    txtStock.setText("");
    txtStockMinimo.setText("");
    txtProveedor.setText("");

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Producto agregado correctamente"
    );

} catch (Exception e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Revisá los datos ingresados"
    );
}
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
       try {

    int filaSeleccionada = tblProductos.getSelectedRow();

    if (filaSeleccionada == -1) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Seleccioná un producto de la tabla"
        );
        return;
    }

    int idProducto = Integer.parseInt(
            tblProductos.getValueAt(filaSeleccionada, 0).toString()
    );

    String nombre = txtNombre.getText();
    String descripcion = txtDescripcion.getText();
    double precio = Double.parseDouble(txtPrecio.getText());
    int stock = Integer.parseInt(txtStock.getText());
    int stockMinimo = Integer.parseInt(txtStockMinimo.getText());
    int idProveedor = Integer.parseInt(txtProveedor.getText());

    Producto producto = new Producto(
            idProducto,
            nombre,
            descripcion,
            precio,
            stock,
            stockMinimo,
            idProveedor
    );

    ProductoDAO productoDAO = new ProductoDAO();
    productoDAO.modificarProducto(producto);

    cargarProductos();

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Producto modificado correctamente"
    );

} catch (Exception e) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Revisá los datos ingresados"
    );
}
    }//GEN-LAST:event_btnModificarActionPerformed

    private void tblProductosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblProductosMouseClicked
        int fila = tblProductos.getSelectedRow();

if (fila != -1) {

    txtNombre.setText(tblProductos.getValueAt(fila, 1).toString());
    txtDescripcion.setText(tblProductos.getValueAt(fila, 2).toString());
    txtPrecio.setText(tblProductos.getValueAt(fila, 3).toString());
    txtStock.setText(tblProductos.getValueAt(fila, 4).toString());
    txtStockMinimo.setText(tblProductos.getValueAt(fila, 5).toString());
    txtProveedor.setText(tblProductos.getValueAt(fila, 7).toString());
}
    }//GEN-LAST:event_tblProductosMouseClicked

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        int filaSeleccionada = tblProductos.getSelectedRow();

if (filaSeleccionada == -1) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Seleccioná un producto de la tabla"
    );

    return;
}

int opcion = javax.swing.JOptionPane.showConfirmDialog(
        this,
        "¿Seguro que querés eliminar este producto?",
        "Confirmar eliminación",
        javax.swing.JOptionPane.YES_NO_OPTION
);

if (opcion == javax.swing.JOptionPane.YES_OPTION) {

    int idProducto = Integer.parseInt(
            tblProductos.getValueAt(filaSeleccionada, 0).toString()
    );

    ProductoDAO productoDAO = new ProductoDAO();
    productoDAO.eliminarProducto(idProducto);

    cargarProductos();

    txtNombre.setText("");
    txtDescripcion.setText("");
    txtPrecio.setText("");
    txtStock.setText("");
    txtStockMinimo.setText("");
    txtProveedor.setText("");

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Producto eliminado correctamente"
    );
}
    }//GEN-LAST:event_btnEliminarActionPerformed

